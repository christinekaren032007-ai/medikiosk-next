export function translateField(lang: Lang, field: InterviewField): { question: string; options?: string[] } {
  if (lang === "en") return { question: field.question, options: field.options };
  const tr = FIELD_TRANSLATIONS[field.id]?.[lang];
  if (!tr) return { question: field.question, options: field.options };
  return { question: tr.question, options: tr.options || field.options };
}

/** Maps a displayed (possibly translated) option label back to the canonical English value that gets stored. */
export function translateOption(lang: Lang, field: InterviewField, displayLabel: string): string {
  if (lang === "en" || !field.options) return displayLabel;
  const tr = FIELD_TRANSLATIONS[field.id]?.[lang];
  if (!tr?.options) return displayLabel;
  const idx = tr.options.indexOf(displayLabel);
  return idx >= 0 ? field.options[idx] : displayLabel;
}

/** Maps a canonical English option value to its display label in the given language. */
export function displayOption(lang: Lang, field: InterviewField, englishValue: string): string {
  if (lang === "en" || !field.options) return englishValue;
  const tr = FIELD_TRANSLATIONS[field.id]?.[lang];
  if (!tr?.options) return englishValue;
  const idx = field.options.indexOf(englishValue);
  return idx >= 0 ? tr.options[idx] : englishValue;
}
